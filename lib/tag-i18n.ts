/**
 * 태그 배열을 영어 로케일에서 영어로 매핑한다.
 * en 외 로케일은 원본 그대로 반환(ja/zh는 번역 파일, ko는 원본이 한국어).
 * 사전에 없는 값은 원문 유지.
 */
export function localizeTags(
  tags: string[] | undefined,
  locale: Locale
): string[] | undefined {
  if (!tags || locale !== "en") return tags;
  return tags.map((tag) => TAG_EN[tag] ?? tag);
}

/**
 * 크롤러가 붙인 한국어 설명 접두어("{지역} 설화에 등장하는 {타입}.")를
 * 영어 로케일에서 영어 문장으로 치환한다. 접두어 뒤 본문은 유지.
 * 접두어가 없으면(이미 영어이거나 순수 한국어 위키 본문) 원문 그대로.
 */
export function localizeDescription(
  d: string,
  locale: Locale,
  countryEn: string,
  typeEn: string
): string {
  if (locale !== "en" || !d) return d;
  const prefix = d.match(/^\s*.+?\s*설화에\s*등장하는\s*.+?\.\s*/);
  if (!prefix) return d;
  const rest = d.slice(prefix[0].length).trim();
  const lead = `A ${typeEn.toLowerCase()} from the folklore of ${countryEn}.`;
  return rest ? `${lead} ${rest}` : lead;
}
